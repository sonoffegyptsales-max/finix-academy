**اعتبارات الشبكة والتخزين.**

الكاميرات تستهلك عرض نطاق أكبر بكثير من أي جهاز ذكي آخر. وعدة منها تبث في آن قد تُشبع وصلة الرفع، فتتدهور كل الأشياء الأخرى في العقار. افحص سعة الرفع قبل تحديد عدة كاميرات، وفضّل إيثرنت سلكيًا حيث يكون المد ممكنًا أصلًا.

وقرر التخزين عمدًا: فبطاقة محلية أو مسجل يبقي اللقطات في الموقع بلا اشتراك لكنه عرضة لسرقة الجهاز نفسه؛ والسحابة تنجو من السرقة لكنها تكلف شهريًا وتعتمد على الاتصال. وكثير من التركيبات تستخدم كليهما بحكمة.

