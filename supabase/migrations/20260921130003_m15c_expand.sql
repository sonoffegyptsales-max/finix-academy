UPDATE public.lessons SET content = $c$Cameras carry legal weight that no other device in this catalogue does. A badly placed camera is not merely ineffective — it can expose both the client and you to a genuine complaint.

**Privacy first, because it is the part with consequences.**

- **Never point a camera at a neighbour's property**, their windows, their garden, or their entrance. This is the complaint that becomes a legal matter, and in many jurisdictions it breaches data protection law regardless of intent.
- **Respect internal boundaries.** No cameras in bathrooms or bedrooms. Where domestic staff are employed, their accommodation and rest areas are off limits.
- **Use privacy masking** where a camera must cover a useful area but its field unavoidably clips something it should not see. Most cameras support masked zones; configure them at installation rather than promising to do it later.
- **Advise the client of their obligations.** Depending on jurisdiction, recording beyond the property boundary may require signage, may create data protection duties, and may require a retention policy. You are not their lawyer, but flagging it is part of a professional handover.

Document the coverage of every camera in the handover pack. If a complaint ever arises, a documented, deliberate coverage plan is a very different position from an undocumented one.

**Light is the technical constraint that decides image quality.**

- **Never face a camera into the sun's path.** A camera looking east is useless at sunrise and one looking west is useless at sunset — exactly the times of day when arrivals and departures happen.
- **Avoid backlighting.** A camera pointed at a doorway with bright sky behind it will silhouette everyone who walks through. Reposition so the light falls on the subject, or specify a camera with genuine wide dynamic range.
- **Check the scene at night, on site.** Infrared illumination reflects hard off nearby walls, glass and rain, and a camera that looks excellent by day can be a white blur after dark.
- **Never mount a camera behind glass.** IR reflects off the pane straight back into the lens and whites out the entire image. This is the single most common self-inflicted camera fault.

**Mounting that produces usable footage.**

Height is a trade-off. Too low and the camera is vulnerable to interference; too high and it captures the tops of heads rather than recognisable faces. Around 2.5 to 3 metres is the usual compromise for identification.

Angle matters more than resolution. A camera at the right angle capturing faces at moderate resolution is far more useful than a high-resolution camera looking down at scalps. For entrances specifically, aim at face height at the point where someone pauses — at a door, at a gate, at the top of steps.

**Coverage planning.** Cover approaches and choke points rather than open areas. A camera on the only path to the front door is worth more than three covering a large lawn nobody crosses.

**Network and storage considerations.**

Cameras consume far more bandwidth than any other smart device. Several streaming simultaneously can saturate an upload link, degrading everything else in the property. Check the upload capacity before specifying multiple cameras, and prefer wired Ethernet where the run is at all achievable.

Decide storage deliberately: local SD or NVR keeps footage on site with no subscription but is vulnerable to theft of the device itself; cloud survives theft but costs monthly and depends on connectivity. Many installations sensibly use both.

**Weatherproofing and cable discipline.**

Confirm the IP rating suits the position, including driven rain on an exposed wall. Form a drip loop in the cable before it enters any enclosure or wall penetration, and seal the penetration properly. Water tracking along a cable into a camera body or into the fabric of the building is a slow, expensive failure.

**Verify at handover.** Walk the coverage of every camera with the client watching the live view, confirm night performance after dark, confirm motion notifications arrive, and confirm the client can retrieve recorded footage themselves — the last one is the function they will need in the one moment that matters.$c$,
