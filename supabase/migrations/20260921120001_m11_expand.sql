**The six families, and the job each one owns.**

**DIY smart switches (BASIC, MINI, DUAL).** Small relay modules that sit *behind* an existing switch or inside a fitting. They do not replace the wall plate, which matters more than it sounds: in a property where the client likes the existing switch plates, or where the plates are a non-standard size, a DIY module lets you add control without touching the visible finish. They need space in the back box or the ceiling rose, and that space is the constraint you check first.

**Smart wall switches (Fusion, M5, T5 series).** These replace the wall plate entirely. Cleaner result, single-visit install, and the client gets a physical button that works when the network is down. The constraint here is the back box: most need 5–7 cm depth, and a 4 cm box is common in older Egyptian construction. Check depth before quoting, not on install day.

**Smart plugs (S26, S60).** Appliance-level control with no wiring at all. The quickest win on any site and the right answer for anything the client might move — fans, heaters, water dispensers, washing machines. Rated current is the whole story: check the appliance's inrush, not its running draw.

**Gateways and sensors (ZBBridge, ZBDongle, motion/contact/temperature).** The gateway is what turns a collection of devices into a system. Zigbee sensors are cheap, battery-powered, and only useful once a gateway and enough mains-powered routers exist to carry the mesh.

**Appliance controllers (TH series, NSPanel, DUALR3).** These control something with logic rather than just switching it — a thermostat, a water heater, a motorised curtain. This is where the margin is, because the job is engineering rather than fitting.

**Cameras (CAM series).** A separate conversation with separate privacy implications, covered in a later module.

**The one decision that determines everything else: retrofit or renovation?**

If the walls are staying closed and the client wants minimal disruption, you are in DIY-module and smart-plug territory, and the limiting factors are back-box space and neutral availability. If the property is being renovated or newly wired, you specify wall switches and pull neutrals everywhere, and almost every constraint disappears.

Answering this one question before opening a catalogue removes about eighty percent of the product range from consideration and makes the rest obvious.

