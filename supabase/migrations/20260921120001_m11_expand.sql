This is the single biggest process mistake in the field, and it is almost always discovered too late.

If you pair every device under *your* installer account and hand the client a shared login, you have created a dependency that will hurt both sides. The client cannot fully control their own home, cannot remove you, and if your account has a problem their house is affected. Meanwhile you are permanently responsible for an account tied to a property you no longer visit.

**The correct pattern:**

1. Create the account **in the client's name, with the client's email**, at the start of the job.
2. Commission everything under that account.
3. Have the client **share access back to you** using eWeLink's sharing feature.
4. At handover the client owns the home. You hold shared access for support, and they can revoke it at any time.

