UPDATE public.lessons SET content = $c$Three protocol families appear in SONOFF deployments, and choosing between them is the most consequential technical decision on a job. Get it wrong and you produce an installation that works on commissioning day and degrades for years.

**Wi-Fi: simple, and it does not scale.**

Every Wi-Fi device joins the home router directly. Setup is trivial, no hub is needed, and range is whatever the router covers. That simplicity is real and it is why Wi-Fi devices sell.

The problems appear with count. Consumer routers commonly start misbehaving somewhere around 30 or so associated clients — not by failing outright, but by dropping and re-associating devices unpredictably. A household already has phones, laptops, a TV and a console on that router before you add anything. Twenty smart devices on top is where "it randomly goes offline" starts, and that call comes to you, not to the router manufacturer.

Wi-Fi devices are also mains-powered by necessity: the radio draws far too much for a battery sensor to be practical.

**Use Wi-Fi for:** small installs, a handful of devices, anything where adding a hub is disproportionate, and devices that need internet access anyway.

**Zigbee 3.0: the answer for scale.**

Zigbee devices do not touch the router. They form their own mesh through a gateway. Three consequences matter:

- **Low power.** A Zigbee contact sensor runs a year or more on a coin cell. Wi-Fi cannot do this.
- **Mesh routing.** Every mains-powered Zigbee device acts as a router for the others. Coverage grows as you add devices, rather than degrading.
- **Local operation.** Automations between Zigbee devices run at the gateway, so they keep working when the internet is down. A motion-triggered light that depends on a cloud round trip is a light with a delay and a failure mode.

The cost is the gateway — one more box, one more thing to place well and power reliably.

**Use Zigbee for:** anything above roughly a dozen devices, all battery sensors, and any automation that must survive an internet outage.

**Matter: the compatibility layer, not a competitor.**

Matter is a standard that lets devices from different manufacturers work in the same ecosystem without vendor bridges. A Matter device can join Apple Home, Google Home and Alexa at once. It runs over Wi-Fi or over Thread — it is not itself a radio.

For an installer the practical value is client-facing: Matter is what lets you promise a client that a device bought today will still work if they change ecosystems in three years. That promise closes deals.

**The rule that prevents most callbacks.**

Count the devices before you choose. Under about ten, Wi-Fi is fine and a gateway is overhead. Above that, Zigbee with a gateway is not a preference — it is what stops the installation degrading as it grows. Mixed installs are normal and correct: Wi-Fi for the few devices that need it, Zigbee for everything else.

The failure to avoid is putting forty Wi-Fi devices on a domestic router because each individual device was simple to commission. Every one of them worked the day you installed it. That is precisely why the pattern keeps happening.$c$,
