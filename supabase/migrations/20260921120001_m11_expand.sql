UPDATE public.lessons SET content = $c$Product selection is a sequence of constraint checks, not a preference. Run them in order and the answer is usually forced — which is exactly what you want, because a forced answer is one you can defend to a client.

**Check 1 — Is there a neutral at the switch position?**

This single question eliminates more product options than everything else combined, and it is the one most often skipped.

Most smart wall switches need line, neutral and load, because the electronics must draw power continuously. Older Egyptian installations frequently have only line and switched-line at the switch box, with the neutral joined at the ceiling rose.

If there is no neutral you have three honest options: a no-neutral-compatible switch (which works by leaking a small current through the load and can cause LED lamps to glow faintly or flicker); a DIY relay module fitted at the ceiling rose where the neutral is; or pulling a neutral, which means chasing walls.

Tell the client which of these applies *before* quoting. A no-neutral switch that makes their new LED downlights glow at night is a callback you cannot fix with configuration.

**Check 2 — Does the back box have depth?**

Smart switches need roughly 5–7 cm. A 4 cm box is common in older construction. You cannot compress the module. Measure during the survey, and if the depth is short, price a deeper back box or plan a DIY module elsewhere in the circuit.

**Check 3 — What is the load type and what is its inrush?**

Resistive loads (heaters, incandescent) are well-behaved. Inductive loads (motors, fans, pumps) draw a starting surge. LED drivers draw a very brief but very high inrush as their input capacitors charge — a bank of LED downlights can peak at many times its running current.

Match the device to the *peak*, not to the nameplate. A relay rated 10 A that runs a 2 A LED bank looks generous and still welds its contacts if the inrush is high enough and it switches often enough.

Dimmers add a further constraint: the lamp must be dimmable and the dimmer must suit its driver type. "Dimmable LED" on a box is not a guarantee of compatibility with a given dimmer.

**Check 4 — Does the client move this appliance?**

If yes, it is a smart plug, regardless of what else would be elegant. Hard-wiring control to a socket the client will unplug something from produces a device that controls nothing.

**Check 5 — Does this need to work when the internet is down?**

Anything safety-adjacent, anything on a stair or entrance, and anything the client relies on daily should keep working offline. That pushes you toward Zigbee with local automation, and away from cloud-dependent Wi-Fi logic.

**Check 6 — How many devices in total?**

Under ten, Wi-Fi is acceptable. Above that, specify a gateway and Zigbee, as covered in the protocol lesson.

**A worked example.** Three-bedroom flat, walls staying closed, client wants lighting control throughout plus the water heater and the AC.

Survey finds: neutrals present in the two newest rooms only, 4 cm boxes in the hallway, water heater on its own 20 A circuit, split AC with an IR remote.

